// The effective table: built-in names plus a project rule's "내장 이름".
export function effectiveGlobals(projectNames = null) {
  const merged = {};
  for (const language of ["javascript", "python"]) {
    const own = projectNames?.[language] || {};
    merged[language] = {
      namespaces: new Set([...BUILT_IN_GLOBALS[language].네임스페이스, ...(own.네임스페이스 || [])]),
      functions: new Set([...BUILT_IN_GLOBALS[language].함수, ...(own.함수 || [])]),
    };
  }
  return merged;
}

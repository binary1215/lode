// Error helpers. `fail(message, code)` is the one throwing shape; failWith and
// failCode keep the defaults of the local helpers they replaced.

export function fail(message, code) {
  throw Object.assign(new Error(message), { code });
}

// A module-level `fail` with a default reason code.
export const failWith =
  (defaultCode) =>
  (message, code = defaultCode) =>
    fail(message, code);

// Code-first form: the message defaults to the code.
export function failCode(code, message = code) {
  return fail(message, code);
}

